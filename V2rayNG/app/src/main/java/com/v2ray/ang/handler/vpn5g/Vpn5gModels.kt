package com.v2ray.ang.handler.vpn5g

/**
 * VPN 5G remote data models.
 *
 * All fields are nullable: Gson allocates these objects without calling the
 * Kotlin constructor, so a field absent from the JSON stays null instead of
 * taking its Kotlin default. Callers must treat null as "not provided".
 */

/** One entry of live_configs.json. */
data class LiveConfigEntry(
    val protocol: String? = null,
    val country: String? = null,
    val ping: String? = null,
    val raw_ping: Int? = null,
    val uri: String? = null,
    val name: String? = null,
    val host: String? = null,
    val port: Int? = null,
)

/** Remote app configuration (app_config.json). */
data class AppConfigRemote(
    /**
     * IGNORED since v1.1.1: the free tier is the 20 fastest-pinging configs
     * (see Vpn5gConstants.FREE_SERVER_COUNT), not a country list. Kept so
     * older published configs still parse.
     */
    val free_countries: List<String>? = null,
    val notice: String? = null,
    val config_sources: List<String>? = null,
    val min_version: String? = null,
    val subscription_status: SubscriptionStatusRemote? = null,
    /** Admin-managed promo codes (discount / gift). Null when the bot side has none. */
    val codes: List<PromoCodeRemote>? = null,
    /** Admin-managed subscription plans. Null = none published (no plan cards). */
    val plans: List<SubscriptionPlanRemote>? = null,
    /** Direct bank payment gateway settings. Null = not configured. */
    val payment_gateway: PaymentGatewayRemote? = null,
    /** Whether the free trial is offered (bot-managed flag). */
    val trial_enabled: Boolean? = null,
    /** Free-trial length in hours (24 per the product rule). */
    val trial_hours: Int? = null,
    /** Admin-published app announcement (v1.1.5): null = none published. */
    val announcement: AnnouncementRemote? = null,
    /** Ads: interstitial + user-submitted ads + pricing (v1.1.15). Null = no ads. */
    val ads: AdsRemote? = null,
    /**
     * Remote commands (v1.1.26, remote-control contract v1): admin
     * commands published by the bot. The array always mirrors the
     * bot's pending list (each publish replaces it whole). Null =
     * key absent = no commands. Executed once per [RemoteCommandRemote.id]
     * — see [Vpn5gRemoteCommands].
     */
    val commands: List<RemoteCommandRemote>? = null,
)

/**
 * One remote command from app_config.json (v1.1.26, contract v1).
 * [payload] stays a raw [com.google.gson.JsonObject] so unknown or
 * future fields never break parsing; the planner in
 * [Vpn5gRemoteCommands] extracts exactly the fields each type needs.
 * [created_at]/[expires_at] are UTC "YYYY-MM-DD HH:MM:SS" (space
 * separator); ISO-8601 with T is also accepted by the parser.
 */
data class RemoteCommandRemote(
    val id: String? = null,
    val type: String? = null,
    val payload: com.google.gson.JsonObject? = null,
    val created_at: String? = null,
    val expires_at: String? = null,
)

/**
 * Admin-published app announcement, from app_config.json (v1.1.5).
 * Set and cleared by the admin through the Telegram bot; published to
 * the HF Space in app_config.json. The app shows it as a dismissible
 * card on the home screen. The [id] is regenerated by the bot whenever
 * the text or image changes, so an edited announcement is shown again
 * even to users who dismissed the previous one.
 */
data class AnnouncementRemote(
    /** True when the announcement is live. */
    val enabled: Boolean? = null,
    /** Announcement text (Persian). Blank = nothing to show. */
    val text: String? = null,
    /** Optional public image URL; null/blank = text only. */
    val image_url: String? = null,
    /** Stable id for one announcement version (dismiss tracking). */
    val id: String? = null,
    /**
     * Optional link (v1.1.15): tapping the announcement text/image
     * opens this URL. Null/blank = the card is not tappable.
     */
    val link_url: String? = null,
)

/**
 * Pure announcement-visibility rules (v1.1.5): show only a live
 * announcement with non-blank text that the user has not dismissed.
 * Dismissal is tracked by [dismissKey] — the announcement id when the
 * bot published one, otherwise the text itself — so editing the text
 * (new id) re-shows it.
 */
object Vpn5gAnnouncement {
    fun shouldShow(announcement: AnnouncementRemote?, dismissedKey: String?): Boolean {
        if (announcement?.enabled != true) return false
        if (announcement.text.isNullOrBlank()) return false
        return dismissKey(announcement) != dismissedKey
    }

    fun dismissKey(announcement: AnnouncementRemote): String {
        val id = announcement.id?.takeIf { it.isNotBlank() }
        if (id != null) return id
        return announcement.text?.trim().orEmpty()
    }
}

/**
 * Ads, from app_config.json (v1.1.15). Everything commercial comes
 * from here — ad content, link, duration, schedule and prices. The
 * app never hardcodes ad content or prices: when the bot publishes
 * no ads, no ad is shown. All fields nullable so older published
 * configs without them still parse.
 */
data class AdsRemote(
    /** Admin interstitial shown on reconnect (null = none). */
    val interstitial: InterstitialAdRemote? = null,
    /** User-submitted ads, approved by the admin (null = none). */
    val user_ads: List<UserAdRemote>? = null,
    /** Prices per ad model, set by the admin (null = not published). */
    val pricing: AdPricingRemote? = null,
)

/**
 * Admin interstitial ad (v1.1.15): a full-screen ad on reconnect.
 * [duration_seconds] is admin-set, allowed range 1–20 (clamped by
 * [Vpn5gAds.clampDuration]); [show_from_connect_number] tunes the
 * frequency (default 2 = from the second connect in an app session);
 * [applies_to_free_only] false includes subscribers (default true =
 * free tier only).
 */
data class InterstitialAdRemote(
    /** True when the interstitial is live. */
    val enabled: Boolean? = null,
    /** Countdown seconds, 1–20. Null = the 10 s default. */
    val duration_seconds: Int? = null,
    /** First connect number that may show it (default 2). */
    val show_from_connect_number: Int? = null,
    /** True = free tier only (default); false = subscribers too. */
    val applies_to_free_only: Boolean? = null,
    /** Ad text (Persian). Blank + no image = nothing to show. */
    val text: String? = null,
    /** Optional public image URL; null/blank = text only. */
    val image_url: String? = null,
    /** Optional link: tapping the ad opens this URL. */
    val link_url: String? = null,
    /** Stable id for one ad version (view/click tracking). */
    val id: String? = null,
)

/**
 * One user-submitted ad (v1.1.15): submitted from the bot's user
 * panel with a preset payment, shown only after admin approval.
 * [model] is one of "once" (1 display), "ten_times" (10 displays at
 * different times), "hourly" (shown in set hour windows) or
 * "monthly_daily" (monthly, 5 displays per day). The caps ARE the
 * purchased amounts — the app never shows more impressions than
 * purchased. [hour_windows] are [start, end) local-hour pairs.
 */
data class UserAdRemote(
    /** Stable id (view/click tracking). */
    val id: String? = null,
    /** Ad text (Persian). */
    val text: String? = null,
    /** Optional public image URL. */
    val image_url: String? = null,
    /** Optional link: tapping the ad opens this URL. */
    val link_url: String? = null,
    /** "once" | "ten_times" | "hourly" | "monthly_daily". */
    val model: String? = null,
    /** Total displays purchased (null = unlimited). */
    val max_impressions: Int? = null,
    /** Displays per day purchased (null = unlimited). */
    val impressions_per_day: Int? = null,
    /** Hour windows as [start, end] pairs, local hours, end-exclusive. */
    val hour_windows: List<List<Int>>? = null,
    /** Price paid for this ad, in Toman (informational). */
    val price_toman: Long? = null,
    /** True when the ad is live (admin-controlled). */
    val enabled: Boolean? = null,
    /** True when the admin approved the ad. */
    val approved: Boolean? = null,
)

/** Ad-model prices, set by the admin in the bot panel (v1.1.15). */
data class AdPricingRemote(
    /** Price of one display, in Toman. */
    val once_toman: Long? = null,
    /** Price of 10 displays at different times, in Toman. */
    val ten_times_toman: Long? = null,
    /** Price of hourly displays in set windows, in Toman. */
    val hourly_toman: Long? = null,
    /** Price of a monthly ad (5 displays per day), in Toman. */
    val monthly_daily_toman: Long? = null,
)

/**
 * One subscription plan, published by the bot side in app_config.json.
 * Prices are NEVER hardcoded in the app: when the bot publishes no plans,
 * the Premium screen shows no plan cards at all.
 */
data class SubscriptionPlanRemote(
    /** Stable id, e.g. "monthly", "yearly". */
    val id: String? = null,
    /** "monthly" or "yearly" (drives the card layout and badge). */
    val period: String? = null,
    /**
     * Duration in days, as published by the bot (v1.1.14). The bot's
     * plan ids are sub_1/sub_3/sub_6/sub_12 = 30/90/180/360 days; when
     * [days] is absent the id (then the period) decides — see
     * [Vpn5gPlans.planDays]. Null = not published.
     */
    val days: Int? = null,
    /** Display name in Persian, e.g. "ماهانه". */
    val name_fa: String? = null,
    /** Price in Toman. Null = price not published (card hidden). */
    val price_toman: Long? = null,
    /**
     * Volume cap in gigabytes, set by the admin for this plan
     * (v1.1.18, Model B: volume or time, whichever first). The bot
     * publishes it per plan in app_config.json; null/absent = no
     * cap (unlimited). The app NEVER invents a cap: when neither
     * [volume_gb] nor [gb] is present the plan is unlimited.
     * When both are set, [volume_gb] wins.
     */
    val volume_gb: Double? = null,
    /**
     * Alias of [volume_gb] (v1.1.18): the field the bot already
     * publishes for the `gb_20` / `gb_50` / `gb_100` / `gb_200`
     * plans in the live app_config.json. Accepted so those plans
     * meter from today; new publishes should use [volume_gb].
     */
    val gb: Double? = null,
)

/**
 * Direct bank payment gateway settings, published by the bot side in
 * app_config.json. The app NEVER hardcodes gateway credentials or test
 * values and never constructs payment requests: when the gateway is
 * configured it opens the published checkout URL in the browser; while
 * it is not configured the option is shown as coming soon and routes the
 * user to the bot to complete the purchase manually.
 *
 * v1.1.30 (config-driven payment methods, Aref's order): the same
 * published block also carries the admin's PAYMENT LINK (a URL +
 * Persian name + guide text the admin can add/change from the bot
 * panel at any time) and the USDT (Tether) wallet (address + network
 * + guide). Every field is nullable: an unpublished method is simply
 * not shown — never a dead button. A future bot-side exchange
 * integration only has to publish these fields; the app needs no
 * update. Payment confirmation/crediting stays server-side through
 * the existing code flow — the app only displays and opens.
 */
data class PaymentGatewayRemote(
    /** True when the gateway is configured and usable. */
    val enabled: Boolean? = null,
    /** Gateway checkout URL the app opens in the browser. */
    val url: String? = null,
    /** Merchant id (informational; the app never sends it anywhere). */
    val merchant_id: String? = null,
    /** Callback URL the gateway returns to (informational; bot-owned). */
    val callback_url: String? = null,
    /** Display name, e.g. "درگاه پرداخت مستقیم بانکی". */
    val name_fa: String? = null,
    /**
     * Admin payment link (v1.1.30): a payment URL the admin manages
     * from the bot panel. Null/blank = the entry is hidden.
     */
    val payment_link_url: String? = null,
    /** Payment-link display name in Persian (null = UI default label). */
    val payment_link_name_fa: String? = null,
    /** Payment-link guide text in Persian, shown under the entry. */
    val payment_link_guide_fa: String? = null,
    /**
     * USDT (Tether) wallet address (v1.1.30). Null/blank = the USDT
     * method is hidden. The app only displays it (copyable); the
     * payment itself is confirmed server-side via the code flow.
     */
    val usdt_address: String? = null,
    /** USDT network label, e.g. "TRC20" (informational). */
    val usdt_network: String? = null,
    /** USDT display name in Persian (null = UI default label). */
    val usdt_name_fa: String? = null,
    /** USDT guide text in Persian, shown under the address. */
    val usdt_guide_fa: String? = null,
)

/**
 * One admin-managed promo code, published by the bot side in app_config.json.
 * The bot is the authority: it creates the codes and decrements
 * [remaining_uses] when they are redeemed. The app only validates against
 * the fetched list and records its own redemptions locally.
 *
 * v1.1.12: the published entries also carry [user_id] (the Telegram id
 * the code was issued for), [expires_at] (ISO-8601 expiry) and [plan]
 * (the plan id a gift grants). All three are nullable so older
 * published configs without them still parse.
 */
data class PromoCodeRemote(
    /** Code as the user types it (matched case-insensitively, trimmed). */
    val code: String? = null,
    /** "discount" or "gift". */
    val type: String? = null,
    /** Discount percent (0-100) when type is "discount". */
    val discount_percent: Int? = null,
    /** Gift duration in days when type is "gift". */
    val gift_days: Int? = null,
    /**
     * Gift duration in HOURS when type is "gift" (v1.1.14): the admin
     * picks 1 / 5 / 24 hours or 7 days for a gift code. When set it
     * wins over [gift_days] (hours are the finer unit); a gift with
     * neither is malformed. 7 days is published as 168 hours.
     */
    val gift_hours: Int? = null,
    /**
     * Tier a gift grants (v1.1.14): "gift" = the middle GIFT tier
     * (more than the 20 free configs, not the full VIP pool, no
     * 30-minute cutoff while it lasts) or a plan id ("sub_1" …)
     * granting a full subscription. Null = a gift with no plan id
     * grants the GIFT tier.
     */
    val tier: String? = null,
    /** Total allowed redemptions, or null for unlimited. */
    val max_uses: Int? = null,
    /** Redemptions left, as last published by the bot. Null = unknown/unlimited. */
    val remaining_uses: Int? = null,
    /**
     * Telegram user id the code was issued for (bot-side grant), or null
     * when the code is not bound to one person. NOTE: the app has no
     * Telegram identity for the signed-in user, so it cannot prove this
     * binding itself — see Vpn5gPromoCodes.
     */
    val user_id: Long? = null,
    /** ISO-8601 expiry ("2027-11-18T19:14:59+00:00"), or null when the code never expires. */
    val expires_at: String? = null,
    /** Plan id the gift grants ("sub_12", "sub_1"), or null when not a plan gift. */
    val plan: String? = null,
)

/** Subscription status as published by the bot side in app_config.json. */
data class SubscriptionStatusRemote(
