/** One live server shown on the home screen. */
data class Vpn5gServerUi(
    val guid: String,
    val name: String,
    val country: String,
    val pingMillis: Long,
    val isSelected: Boolean,
    /** True when this server is in the free tier (top-20 fastest ping, v1.1.2). */
    val isFree: Boolean = false,
    /** Flag emoji derived from the remark or the server IP ("🌐" when unknown). */
    val flag: String = "🌐",
    /** Persian country name derived from the remark or the server IP. */
    val countryNameFa: String = "",
    /** ISO country code, or "" when unknown. */
    val countryCode: String = "",
    /** Server host (for GeoIP lookup only; not displayed). */
    val host: String = "",
    /** True when this server passed a real through-the-proxy ping test
     * (v1.1.7): the delay was measured by sending a real request through
     * the proxy, not by a raw TCP connect. Only real-pinged servers can
     * be free or auto-picked; a TCP-only ping is never shown as a number. */
    val hasRealPing: Boolean = false,
    /**
     * True when this server comes from the bundled seed snapshot
     * (v1.1.20): it was TCP-verified at build time and is free-eligible
     * with an unknown ping until the real probe measures it. A seed
     * server the real probe fails is never seed-trusted again (its ping
     * is withdrawn to -1). The seed is a starting point, never proof —
     * the connect chain still verifies the tunnel.
     */
    val isSeed: Boolean = false,
    /** Config protocol scheme ("vless", "vmess", "trojan", "ss"), or "" when unknown. */
    val protocol: String = "",
    /**
     * True when this server already verified on the CURRENT network
     * operator (v1.1.14): the app's own verification history prefers
     * it for this operator. False with no history — never invented.
     */
    val operatorVerified: Boolean = false,
    /**
     * Server identity (scheme://host:port:identity, v1.1.24) — the
     * stable key the health-score memory and real-ping evidence use
     * across refreshes (GUIDs are re-issued every refresh). "" when
     * unknown (tests / legacy constructions).
     */
    val dedupeKey: String = "",
)

/** One country section on the home screen. */
data class Vpn5gCountryUi(
    val label: String,
    val isFree: Boolean,
    val servers: List<Vpn5gServerUi>,
)
